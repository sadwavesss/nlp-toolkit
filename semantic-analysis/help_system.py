def get_help(topic_key: str) -> Dict:
    return HELP_TOPICS.get(topic_key, {"title": "Справка", "content": "Раздел не найден"})


def get_all_topics() -> List[Dict]:
    return [{"key": k, "title": v["title"]} for k, v in HELP_TOPICS.items()]


def search_help(query: str) -> List[Dict]:
    q = query.lower()
    results = []
    for k, v in HELP_TOPICS.items():
        if q in v["title"].lower() or q in v["content"].lower():
            results.append({"key": k, "title": v["title"]})
    return results
