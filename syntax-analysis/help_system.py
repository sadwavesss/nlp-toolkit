def get_help(topic: str = "general") -> dict:
    return HELP_TOPICS.get(topic, HELP_TOPICS["general"])


def get_all_topics() -> list:
    return [{"key": k, "title": v["title"]} for k, v in HELP_TOPICS.items()]


def search_help(query: str) -> list:
    query = query.lower()
    results = []
    for key, topic in HELP_TOPICS.items():
        if query in topic["title"].lower() or query in topic["content"].lower():
            results.append({"key": key, "title": topic["title"]})
    return results
