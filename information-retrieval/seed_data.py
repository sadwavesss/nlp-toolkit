def main():
    app = create_app()
    with app.app_context():
        from app.db import get_db, init_db

        init_db()
        for title, text, date in SAMPLE_DOCUMENTS:
            doc = Document(title=title, text=text, date=date, time="12:00:00")
            doc.add_document_to_base()
        db = get_db()
        count = db.execute("SELECT COUNT(*) AS c FROM documents").fetchone()["c"]
        lemmas = db.execute("SELECT COUNT(*) AS c FROM lemmas").fetchone()["c"]
        print(f"Добавлено документов: {count}")
        print(f"Уникальных лемм в индексе: {lemmas}")


if __name__ == "__main__":
    main()
